/**
 * Trả về chuỗi SVG cho một icon.
 *
 * @param {string} name  khoá trong PATHS
 * @param {{size?:number, cls?:string, stroke?:number, fill?:boolean, label?:string}} [opts]
 *   `label` đặt aria-label và role="img"; bỏ trống thì icon là trang trí
 *   (aria-hidden) — đúng cho icon đứng cạnh chữ đã có nghĩa.
 */
export function icon(name, opts = {}) {
  const { size = 18, cls = '', stroke = 1.6, fill = false, label = '' } = opts;
  const d = PATHS[name];
  if (!d) {
    console.warn('[icons] unknown icon:', name);
    return '';
  }
  const a11y = label
    ? `role="img" aria-label="${label}"`
    : 'aria-hidden="true" focusable="false"';
  return `<svg class="i ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    `fill="${fill ? 'currentColor' : 'none'}" stroke="currentColor" stroke-width="${stroke}" ` +
    `stroke-linecap="round" stroke-linejoin="round" ${a11y}>${d}</svg>`;
}

/** Icon nằm trong khung vuông có nền — dùng cho feature card, empty state. */
export function iconBox(name, { size = 20, tone = '', label = '' } = {}) {
  return `<span class="ic-box ${tone}">${icon(name, { size, label })}</span>`;
}

